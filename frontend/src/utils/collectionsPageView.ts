/**
 * What the Library page's Collections tab draws beyond what `collectionKinds`
 * works out from the read: what each list row states in place of a count, what
 * each pane says, how many table rows are painted, and what a batch write asks
 * first. Every surface that draws the tab reads it, so the QAM page and the
 * desktop's Library tab say the same about the same collections.
 *
 * Structure and vocabulary: `docs/architecture/qam-panel.md`, section Library.
 */

import {
  KIND_TEXT,
  foreignCount,
  kindMembers,
  onCount,
  romCountLabel,
  type CollectionsKindId,
  type FavoritesAnswer,
  type TableKindId,
} from "./collectionKinds";
import type { CollectionsPageState } from "./useCollectionsPage";

/** How many rows the table paints. The autogenerated kinds run to hundreds, and
 *  painting them all strains Steam's renderer; the search narrows below it,
 *  and Enable all / Disable all reach past it. */
export const COLLECTION_RENDER_CAP = 50;

export const AUTOGENERATED_TITLE = "Autogenerated";
export const SEARCH_LABEL = "Search";
export const ENABLE_ALL_LABEL = "Enable all";
export const DISABLE_ALL_LABEL = "Disable all";
export const TABLE_HEADINGS = {
  collection: "Collection",
  owner: "Owner",
  roms: "ROMs",
  inSteam: "In Steam",
  sync: "Sync",
} as const;

// --- What a list row states in place of a count ---

/**
 * What the owner switch's row states in place of a count: the number of other
 * users' collections alone, the pane saying whether they are shown; a dash
 * where the read failed, as the kind rows do; and nothing while the read is out
 * or while Tender cannot yet tell whose a collection is.
 */
export function ownerCount(state: CollectionsPageState): string {
  if (state.load.state === "failed") return "—";
  if (state.load.state !== "loaded") return "";
  const foreign = foreignCount(state.collections);
  if (foreign === null) return "";
  return String(foreign);
}

/** What the Favorites row states in place of a count. */
export function favoritesCount(state: CollectionsPageState, favorites: FavoritesAnswer): string {
  if (state.load.state === "failed") return "—";
  if (state.load.state !== "loaded") return "";
  switch (favorites.state) {
    case "one":
      return romCountLabel(favorites.collection.rom_count);
    case "several":
      return "more than one, listed under Collections";
    case "none":
      return "—";
  }
}

export function kindCount(state: CollectionsPageState, kind: CollectionsKindId, favorites: FavoritesAnswer): string {
  if (state.load.state === "failed") return "—";
  if (state.load.state !== "loaded") return "";
  return onCount(kindMembers(state.collections, kind, state.ownerScope, favorites));
}

// --- The panes ---

/** Why the listing is not there, where a table or a count would be. */
export const loadFailedLines = (message: string | null | undefined): [string, string] => [
  message ?? "Could not read your collections from RomM.",
  "Leave this tab and come back to ask again.",
];

/** What the Favorites pane says about the one favorites collection, the several, or none. */
export function favoritesLine(favorites: FavoritesAnswer): string {
  switch (favorites.state) {
    case "one":
      return `${romCountLabel(favorites.collection.rom_count)} in it`;
    case "several":
      return (
        "More than one favorites collection counts as yours — until Tender knows your RomM account, another user's " +
        "public one counts too — so the Favorites switch cannot stand for them. They are listed under Collections, " +
        "each with its own switch."
      );
    case "none":
      return "Your RomM account has no favorites collection.";
  }
}

export const OWNER_ABOUT = "their public ones, on a shared RomM server";
export const OWNER_SENTENCE =
  "Turned off, other users' collections are hidden here and left out of the sync, even ones you switched on; " +
  "turning it back on brings those choices back. Tender can tell whose a collection is only once it knows your RomM " +
  "account, and until then nothing is hidden.";

/** What the owner pane says about other users' collections now, once the listing is in. */
export function ownerLine(foreign: number | null, scope: CollectionsPageState["ownerScope"]): string {
  if (foreign === null) return "Tender does not know your RomM account yet, so nothing is hidden for now.";
  if (foreign === 0) return "No collections from other users right now.";
  return `${foreign} from other users right now — ${scope === "all" ? "shown, and synced where switched on" : "hidden and left out of the sync"}.`;
}

/** What a kind's pane says where its table has no row: nothing listed, or nothing matching. */
export const kindEmptyLine = (kind: TableKindId, searched: boolean): string =>
  searched
    ? `Nothing under ${KIND_TEXT[kind].name} matches the search.`
    : `Nothing to list under ${KIND_TEXT[kind].name}.`;

export const hiddenForeignLine = (hidden: number): string =>
  `${hidden} from other users ${hidden === 1 ? "is" : "are"} hidden while Other users' collections is off.`;

export const overflowLine = (overflow: number): string => `${overflow} more — refine the search to reach them.`;

/**
 * What Enable all / Disable all asks before it writes more than `CONFIRM_ABOVE`
 * collections: which ones, including those past the table's cap, and when the
 * change takes effect.
 */
export function setAllConfirm(
  kind: TableKindId,
  count: number,
  enabled: boolean,
  searched: boolean,
): { title: string; description: string; confirm: string; cancel: string } {
  const name = KIND_TEXT[kind].name;
  const verb = enabled ? "Enable" : "Disable";
  const past =
    count > COLLECTION_RENDER_CAP ? `, including those past the first ${COLLECTION_RENDER_CAP} the table shows` : "";
  const which = searched
    ? `the ${count} collections under ${name} that match the search`
    : `all ${count} collections listed under ${name}`;
  const effect = enabled
    ? "Their games come to Steam at the next sync, including games on platforms you do not sync."
    : "It takes effect at the next sync.";
  return {
    title: searched ? `${verb} the ${count} matching in ${name}?` : `${verb} all ${count} in ${name}?`,
    description: `This turns ${enabled ? "on" : "off"} syncing for ${which}${past}. ${effect}`,
    confirm: `${verb} all`,
    cancel: "Cancel",
  };
}
