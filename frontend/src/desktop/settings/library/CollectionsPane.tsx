/**
 * The desktop's Collections: the kinds fill the tab, with the Favorites switch
 * and the owner switch in their rows as on the QAM, and a row's name opens its
 * pane in the list's place (`DrillDown`). What each says, what a row counts and
 * when a batch write asks first are `utils/collectionKinds.ts`'s and
 * `utils/collectionsPageView.ts`'s.
 */

import { Fragment, useState, type FC, type ReactNode } from "react";
import { DialogButton, Spinner, TextField, ToggleField } from "@decky/ui";
import { FaChevronRight } from "react-icons/fa";
import type { CollectionSyncSetting } from "../../../types";
import {
  CONFIRM_ABOVE,
  KIND_ORDER,
  KIND_TEXT,
  OWNER_ROW_NAME,
  foreignCount,
  hiddenForeignCount,
  inSteamLabel,
  kindSentence,
  ownerLabel,
  resolveFavorites,
  type CollectionsKindId,
  type FavoritesAnswer,
  type TableKindId,
} from "../../../utils/collectionKinds";
import {
  AUTOGENERATED_TITLE,
  COLLECTION_RENDER_CAP,
  DISABLE_ALL_LABEL,
  ENABLE_ALL_LABEL,
  OWNER_ABOUT,
  OWNER_SENTENCE,
  SEARCH_LABEL,
  TABLE_HEADINGS,
  favoritesCount,
  favoritesLine,
  hiddenForeignLine,
  kindCount,
  kindEmptyLine,
  loadFailedLines,
  overflowLine,
  ownerCount,
  ownerLine,
  setAllConfirm,
} from "../../../utils/collectionsPageView";
import { detach } from "../../../utils/detach";
import { shownCollections, type CollectionsPageState } from "../../../utils/useCollectionsPage";
import { DesktopConfirmDialog } from "../../gameview/dialogs/DesktopConfirmDialog";
import type { AskDialog } from "../../gameview/dialogs/useDialogHost";
import { DrillDown } from "../DrillDown";
import {
  BUTTON_ROW_STYLE,
  BUTTON_STYLE,
  DETAIL_TITLE_STYLE,
  LIST_HEADING_STYLE,
  LIST_ROW_STYLE,
  MUTED,
  MUTED_TEXT_STYLE,
  NUMERIC_STYLE,
  SELECT_BUTTON_STYLE,
  TABLE_STYLE,
  TD_STYLE,
  TEXT,
  TH_STYLE,
} from "../settingsStyles";

const RULE_STYLE = { borderTop: "1px solid rgba(255, 255, 255, 0.1)", margin: "8px 0 4px" } as const;

/** A row's name and, beside it, what it states in place of a count. */
const RowLabel: FC<{ name: string; count: string }> = ({ name, count }) => (
  <span style={{ display: "flex", alignItems: "baseline", gap: "8px", width: "100%" }}>
    <span style={{ flex: "1 1 auto", minWidth: 0 }}>{name}</span>
    <span data-testid="row-count" style={{ fontSize: "12px", color: MUTED, textAlign: "right" }}>
      {count}
    </span>
    <FaChevronRight size={10} color={MUTED} style={{ flexShrink: 0, alignSelf: "center" }} />
  </span>
);

const KindList: FC<{
  state: CollectionsPageState;
  favorites: FavoritesAnswer;
  onOpen: (id: CollectionsKindId | "owner") => void;
}> = ({ state, favorites, onOpen }) => {
  const favoritesRow = favorites.state === "one" ? favorites.collection : null;
  /** A row: its name and count open its pane, and *toggle* — the row's own switch, where it has one — sits beside them. */
  const row = (id: CollectionsKindId | "owner", name: string, count: string, toggle?: ReactNode) => (
    <div key={id} data-testid={`kind-row-${id}`} style={LIST_ROW_STYLE}>
      <button type="button" style={SELECT_BUTTON_STYLE} onClick={() => onOpen(id)}>
        <RowLabel name={name} count={count} />
      </button>
      {toggle}
    </div>
  );
  return (
    <div data-testid="kind-list">
      {KIND_ORDER.map((kind) => {
        if (kind === "favorites") {
          return (
            <Fragment key={kind}>
              <div style={RULE_STYLE} />
              {row(
                kind,
                KIND_TEXT.favorites.name,
                favoritesCount(state, favorites),
                <ToggleField
                  checked={favoritesRow?.sync_enabled ?? false}
                  disabled={favoritesRow === null}
                  bottomSeparator="none"
                  onChange={(value: boolean) => {
                    if (favoritesRow) state.toggleCollection(favoritesRow, value, "list");
                  }}
                />,
              )}
            </Fragment>
          );
        }
        return (
          <Fragment key={kind}>
            {kind === "franchise" && <div style={LIST_HEADING_STYLE}>{AUTOGENERATED_TITLE}</div>}
            {row(kind, KIND_TEXT[kind].name, kindCount(state, kind, favorites))}
          </Fragment>
        );
      })}
      {row(
        "owner",
        OWNER_ROW_NAME,
        ownerCount(state),
        <ToggleField
          checked={state.ownerScope === "all"}
          bottomSeparator="none"
          onChange={(value: boolean) => state.setOwnerScope(value ? "all" : "own")}
        />,
      )}
      {state.listStatus && (
        <div role="status" data-testid="collections-list-status" style={MUTED_TEXT_STYLE}>
          {state.listStatus}
        </div>
      )}
    </div>
  );
};

const Title: FC<{ name: string; about: string }> = ({ name, about }) => (
  <div style={{ display: "flex", alignItems: "baseline", gap: "10px", marginBottom: "4px" }}>
    <span style={DETAIL_TITLE_STYLE}>{name}</span>
    <span style={{ fontSize: "13px", color: MUTED }}>{about}</span>
  </div>
);

const Sentence: FC<{ text: string }> = ({ text }) => (
  <div data-testid="collections-sentence" style={{ ...MUTED_TEXT_STYLE, color: TEXT }}>
    {text}
  </div>
);

/** What stands where the listing would be while it is not there. */
const LoadState: FC<{ state: CollectionsPageState }> = ({ state }) => {
  if (state.load.state === "failed") {
    const [failed, retry] = loadFailedLines(state.load.message);
    return (
      <div data-testid="collections-load-failed">
        <div style={MUTED_TEXT_STYLE}>{failed}</div>
        <div style={MUTED_TEXT_STYLE}>{retry}</div>
      </div>
    );
  }
  return <Spinner width={24} height={24} />;
};

const FavoritesPane: FC<{ state: CollectionsPageState; favorites: FavoritesAnswer }> = ({ state, favorites }) => (
  <>
    <Title name={KIND_TEXT.favorites.name} about={KIND_TEXT.favorites.about} />
    {favorites.state === "one" && <Sentence text={kindSentence("favorites")} />}
    {state.load.state !== "loaded" ? (
      <LoadState state={state} />
    ) : (
      <div style={MUTED_TEXT_STYLE}>{favoritesLine(favorites)}</div>
    )}
  </>
);

const OwnerPane: FC<{ state: CollectionsPageState }> = ({ state }) => (
  <>
    <Title name={OWNER_ROW_NAME} about={OWNER_ABOUT} />
    <Sentence text={OWNER_SENTENCE} />
    {state.load.state !== "loaded" ? (
      <LoadState state={state} />
    ) : (
      <div style={MUTED_TEXT_STYLE}>{ownerLine(foreignCount(state.collections), state.ownerScope)}</div>
    )}
  </>
);

const CollectionRow: FC<{ collection: CollectionSyncSetting; owned: boolean; state: CollectionsPageState }> = ({
  collection,
  owned,
  state,
}) => (
  <tr data-testid="collection-row">
    <td style={TD_STYLE} title={collection.name}>
      {collection.name}
    </td>
    {owned && <td style={{ ...TD_STYLE, color: MUTED }}>{ownerLabel(collection)}</td>}
    <td style={{ ...TD_STYLE, ...NUMERIC_STYLE }}>{collection.rom_count}</td>
    <td style={{ ...TD_STYLE, ...NUMERIC_STYLE }}>{inSteamLabel(collection)}</td>
    <td style={{ ...TD_STYLE, width: "60px" }}>
      <ToggleField
        checked={collection.sync_enabled}
        bottomSeparator="none"
        onChange={(value: boolean) => state.toggleCollection(collection, value, "pane")}
      />
    </td>
  </tr>
);

const KindPane: FC<{ state: CollectionsPageState; kind: TableKindId; favorites: FavoritesAnswer; ask: AskDialog }> = ({
  state,
  kind,
  favorites,
  ask,
}) => {
  const owned = KIND_TEXT[kind].owned;
  const loaded = state.load.state === "loaded";
  const shown = loaded ? shownCollections(state) : [];
  const rendered = shown.slice(0, COLLECTION_RENDER_CAP);
  const overflow = shown.length - rendered.length;
  const setAll = (enabled: boolean) => {
    if (shown.length <= CONFIRM_ABOVE) {
      state.setAllShown(enabled);
      return;
    }
    const words = setAllConfirm(kind, shown.length, enabled, state.search !== "");
    detach(
      (async () => {
        const yes = await ask(false, (resolve) => (
          <DesktopConfirmDialog
            titleId="tender-settings-collections-set-all-title"
            title={words.title}
            description={words.description}
            confirmLabel={words.confirm}
            cancelLabel={words.cancel}
            onChoice={resolve}
          />
        ));
        if (yes) state.setAllShown(enabled);
      })(),
    );
  };

  let body;
  if (!loaded) body = <LoadState state={state} />;
  else if (shown.length === 0) {
    const hidden = hiddenForeignCount(state.collections, kind, state.ownerScope, favorites);
    body = (
      <>
        <div style={MUTED_TEXT_STYLE}>{kindEmptyLine(kind, state.search !== "")}</div>
        {state.search === "" && hidden > 0 && <div style={MUTED_TEXT_STYLE}>{hiddenForeignLine(hidden)}</div>}
      </>
    );
  } else {
    const numeric = { ...TH_STYLE, ...NUMERIC_STYLE };
    body = (
      <>
        <table style={TABLE_STYLE} data-testid="collections-table">
          <thead>
            <tr>
              <th style={TH_STYLE}>{TABLE_HEADINGS.collection}</th>
              {owned && <th style={TH_STYLE}>{TABLE_HEADINGS.owner}</th>}
              <th style={numeric}>{TABLE_HEADINGS.roms}</th>
              <th style={numeric}>{TABLE_HEADINGS.inSteam}</th>
              <th style={TH_STYLE}>{TABLE_HEADINGS.sync}</th>
            </tr>
          </thead>
          <tbody>
            {rendered.map((collection) => (
              <CollectionRow
                key={`${collection.kind}:${collection.id}`}
                collection={collection}
                owned={owned}
                state={state}
              />
            ))}
          </tbody>
        </table>
        {overflow > 0 && <div style={MUTED_TEXT_STYLE}>{overflowLine(overflow)}</div>}
      </>
    );
  }

  return (
    <>
      <Title name={KIND_TEXT[kind].name} about={KIND_TEXT[kind].about} />
      <Sentence text={kindSentence(kind)} />
      <div style={{ ...BUTTON_ROW_STYLE, alignItems: "flex-end" }}>
        <div data-testid="collections-search" style={{ flex: "1 1 160px", minWidth: 0 }}>
          <TextField label={SEARCH_LABEL} value={state.search} onChange={(e) => state.setSearch(e.target.value)} />
        </div>
        <DialogButton style={BUTTON_STYLE} disabled={shown.length === 0} onClick={() => setAll(true)}>
          {ENABLE_ALL_LABEL}
        </DialogButton>
        <DialogButton style={BUTTON_STYLE} disabled={shown.length === 0} onClick={() => setAll(false)}>
          {DISABLE_ALL_LABEL}
        </DialogButton>
      </div>
      {state.paneStatus && (
        <div role="status" data-testid="collections-pane-status" style={MUTED_TEXT_STYLE}>
          {state.paneStatus}
        </div>
      )}
      {body}
    </>
  );
};

export const CollectionsPane: FC<{ state: CollectionsPageState; ask: AskDialog }> = ({ state, ask }) => {
  const [open, setOpen] = useState(false);
  const favorites = resolveFavorites(state.collections);
  const kind = state.selectedKind;
  const openKind = (id: CollectionsKindId | "owner") => {
    state.select(id);
    setOpen(true);
  };
  let pane;
  if (kind === "owner") pane = <OwnerPane state={state} />;
  else if (kind === "favorites") pane = <FavoritesPane state={state} favorites={favorites} />;
  else pane = <KindPane state={state} kind={kind} favorites={favorites} ask={ask} />;
  return (
    <DrillDown
      open={open}
      onBack={() => setOpen(false)}
      list={<KindList state={state} favorites={favorites} onOpen={openKind} />}
      detail={pane}
    />
  );
};
